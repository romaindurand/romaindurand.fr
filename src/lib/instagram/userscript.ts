/**
 * Userscript ViolentMonkey : un bouton sur instagram.com envoie les cookies de session au blog.
 * `GM_cookie` lit aussi les cookies HttpOnly (à autoriser dans les réglages de ViolentMonkey).
 */
export function buildUserscript(origin: string): string {
	const host = new URL(origin).hostname;
	return [
		'// ==UserScript==',
		'// @name         Blog : envoyer la session Instagram',
		'// @namespace    romaindurand.fr',
		'// @version      1.0.0',
		'// @description  Envoie la session Instagram au blog en un clic',
		'// @match        https://www.instagram.com/*',
		'// @grant        GM_cookie',
		'// @grant        GM_xmlhttpRequest',
		'// @grant        GM_getValue',
		'// @grant        GM_setValue',
		'// @grant        GM_registerMenuCommand',
		`// @connect      ${host}`,
		'// ==/UserScript==',
		'',
		'(function () {',
		"	'use strict';",
		`	const BASE = ${JSON.stringify(origin)};`,
		'',
		'	function notify(text) {',
		"		const box = document.createElement('div');",
		'		box.textContent = text;',
		"		box.setAttribute('role', 'status');",
		"		box.style.cssText = 'position:fixed;right:16px;bottom:72px;z-index:2147483647;padding:12px 16px;background:#111;color:#eee;border:2px solid #eee;font:14px system-ui,sans-serif;max-width:320px';",
		'		document.body.appendChild(box);',
		'		setTimeout(function () { box.remove(); }, 6000);',
		'	}',
		'',
		'	function getToken() {',
		"		let token = GM_getValue('token', '');",
		'		if (!token) {',
		"			token = (prompt(\"Jeton d'ingestion du blog (page /admin/instagram) :\") || '').trim();",
		"			if (token) GM_setValue('token', token);",
		'		}',
		'		return token;',
		'	}',
		'',
		'	function send() {',
		'		const token = getToken();',
		"		if (!token) return notify('Jeton manquant.');",
		'		GM_cookie.list({ url: location.origin }, function (cookies, error) {',
		'			if (error || !cookies) {',
		'				return notify("Lecture des cookies impossible : autorisez l\'accès HttpOnly dans ViolentMonkey (réglages avancés, puis réglages du script).");',
		'			}',
		'			const map = {};',
		'			cookies.forEach(function (cookie) { map[cookie.name] = cookie.value; });',
		'			if (!map.sessionid) {',
		'				return notify("Cookie sessionid introuvable : êtes-vous connecté ? L\'accès HttpOnly est-il autorisé ?");',
		'			}',
		'			GM_xmlhttpRequest({',
		"				method: 'POST',",
		"				url: BASE + '/api/instagram/session',",
		"				headers: { 'Content-Type': 'application/json', Authorization: 'Bearer ' + token },",
		'				data: JSON.stringify({ cookies: map }),',
		'				onload: function (response) {',
		"					if (response.status === 200) return notify('Session envoyée au blog.');",
		'					if (response.status === 401) {',
		"						GM_setValue('token', '');",
		"						return notify('Jeton refusé : cliquez à nouveau pour le ressaisir.');",
		'					}',
		"					notify('Erreur ' + response.status + ' : ' + response.responseText);",
		'				},',
		"				onerror: function () { notify('Blog injoignable.'); }",
		'			});',
		'		});',
		'	}',
		'',
		"	GM_registerMenuCommand('Envoyer la session au blog', send);",
		"	const button = document.createElement('button');",
		"	button.type = 'button';",
		"	button.textContent = 'Envoyer la session au blog';",
		"	button.style.cssText = 'position:fixed;right:16px;bottom:16px;z-index:2147483647;min-height:44px;padding:0 16px;background:#111;color:#eee;border:2px solid #eee;font:700 14px system-ui,sans-serif;cursor:pointer';",
		"	button.addEventListener('click', send);",
		'	document.body.appendChild(button);',
		'})();',
		''
	].join('\n');
}
